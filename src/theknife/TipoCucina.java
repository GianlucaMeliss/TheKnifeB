    public static TipoCucina fromString(String input) {
        if (input == null) return null;

        String normalized = input.trim().toUpperCase();

        // Sostituisce accenti e caratteri speciali prima di tutto
        normalized = normalized
                .replace("É", "E")
                .replace("È", "E")
                .replace("Ç", "C")
                .replace("Ø", "O");

        // Sostituisce spazi, slash, trattini (anche multipli) con underscore singolo
        normalized = normalized.replaceAll("[ /\\-]+", "_");

        // Riduce underscore multipli a uno solo (utile se sopra genera più underscore)
        normalized = normalized.replaceAll("_+", "_");

        try {
            return TipoCucina.valueOf(normalized);
        } catch (IllegalArgumentException e) {
            System.err.println("Tipo cucina non riconosciuto: " + input);
            return null;
        }
    }

